"""Generate Android resources from the shared iOS string catalogs and check parity."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = {"en": "values", "zh-Hans": "values-zh-rCN", "ja": "values-ja", "ko": "values-ko"}
ENTRY = re.compile(r'("(?:\\.|[^"\\])*")\s*=\s*("(?:\\.|[^"\\])*")\s*;')
PLACEHOLDER = re.compile(r"%(?:(\d+)\$)?(?:[-+0 #]*\d*(?:\.\d+)?)(?:ll|l)?([@diuoxXfFeEgGs])")
# Brand names, protocol identifiers and format examples deliberately stay verbatim.
INVARIANTS = {
    "CardBal", "CardBal Android", "FeliCa", "ISO7816", "ISO 7816", "DESFire", "Calypso",
    "UID", "IDm", "PMm", "AID", "SW1SW2", "SELECT", "IDSAM", "NTEP", "NTSAM",
    "KORAIL KOTRIS", "KS X 6924", "Snapper", "Snapper+", "Snapper Plus", "NETS FlashPay",
    "Opal", "Waltti", "Clipper", "EZL", "Cashbee", "EZL / Cashbee", "Navigo", "Rav-Kav",
    "Kartu Multi Trip", "IruCa", "Ryuto", "Rakuten Edy", "Edy", "Suica", "PASMO",
    "ICOCA", "SUGOCA", "TOICA", "Kitaca", "Hayakaken", "Manaca", "Nimoca", "manaca",
    "nimoca", "OKICA", "WAON", "nanaco", "T-money", "U-Money", "EZLink",
    "Lignes d'Azur card", "Lignes d’Azur", "GitHub", "VIEW ALTTE", "VIEW", "PiTaPa", "MRT",
    "ISO 14443", "iCloud", "iPhone NFC", "T-Union",
    "XX123 A456...", "YYYY-MM-DD", "DD/MM/YYYY", "MM/DD/YYYY", "MMM d, yyyy",
}


def catalogs():
    tables = {}
    for language in LANGUAGES:
        entries = ENTRY.findall((ROOT / f"ios/CardBal/Resources/{language}.lproj/Localizable.strings").read_text())
        table = {}
        for raw_key, raw_value in entries:
            key, value = json.loads(raw_key), json.loads(raw_value)
            if key in table:
                raise ValueError(f"{language}: duplicate key {key!r}")
            table[key] = value
        tables[language] = table
    return tables


def placeholders(value):
    return sorted((int(m[1]) if m[1] else i, "text" if m[2] in "@s" else "number")
                  for i, m in enumerate(PLACEHOLDER.finditer(value), 1))


def resource_name(key):
    return "text_" + hashlib.sha256(key.encode()).hexdigest()[:16]


def outputs(tables):
    base = tables["en"]
    result = {}
    for language, directory in LANGUAGES.items():
        rows = [f'    <string name="{resource_name(key)}" formatted="false">'
                f'{escape(json.dumps(tables[language][key], ensure_ascii=False))}</string>'
                for key in sorted(base)]
        result[ROOT / f"android/app/src/main/res/{directory}/localized.xml"] = (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/localization.py from the shared catalogs. -->\n'
            "<resources>\n" + "\n".join(rows) + "\n</resources>\n"
        )
    aliases = dict.fromkeys(base)
    for key, value in base.items():
        if value not in aliases:
            aliases[value] = key
    rows = [f"    {json.dumps(key, ensure_ascii=False).replace('$', chr(92) + '$')} to R.string.{resource_name(alias or key)},"
            for key, alias in sorted(aliases.items())]
    result[ROOT / "android/app/src/main/java/ad/neko/cardbal/android/ui/LocalizedResources.kt"] = (
        "// Generated by tools/localization.py. Do not edit.\n"
        "package ad.neko.cardbal.android.ui\n\n"
        "import ad.neko.cardbal.android.R\n\n"
        "internal val localizedResources = mapOf(\n" + "\n".join(rows) + "\n)\n"
    )
    return result


def check(tables):
    base = tables["en"]
    errors = []
    for language, table in tables.items():
        missing, extra = base.keys() - table.keys(), table.keys() - base.keys()
        if missing or extra:
            errors.append(f"{language}: missing {sorted(missing)}, extra {sorted(extra)}")
        for key in base.keys() & table.keys():
            if not table[key].strip() and base[key].strip():
                errors.append(f"{language}: empty translation for {key!r}")
            if placeholders(base[key]) != placeholders(table[key]):
                errors.append(f"{language}: placeholder mismatch for {key!r}")
            if (language != "en" and table[key] == base[key] and base[key] not in INVARIANTS
                    and re.search(r"[A-Za-z]{2}", PLACEHOLDER.sub("", base[key]))):
                errors.append(f"{language}: untranslated English value for {key!r}")
    return errors


def is_covered(text, tables, depth=0):
    if not text.strip() or depth > 4:
        return True
    known = set(tables["en"]) | set(tables["en"].values()) | INVARIANTS
    if text in known or not re.search(r"[A-Za-z]{2}", text):
        return True
    for key in known:
        if not PLACEHOLDER.search(key):
            continue
        parts, offset = [], 0
        for match in PLACEHOLDER.finditer(key):
            parts += [re.escape(key[offset:match.start()]), ".+?" if match[2] in "@s" else "[-+0-9A-Fa-f.,]+"]
            offset = match.end()
        if re.fullmatch("".join(parts) + re.escape(key[offset:]), text, re.S):
            return True
    if " (" in text and text.endswith(")") and is_covered(text.split(" (")[0], tables, depth + 1):
        return True
    for separator in ["\n", " · ", ": ", " / ", " + ", " → ", " -> "]:
        if separator in text and all(is_covered(part, tables, depth + 1) for part in text.split(separator)):
            return True
    return False


def source_errors(tables):
    errors = []
    swift_calls = re.compile(
        r'(?:Text|Label|Button|Toggle|Picker|Section|Link|ColorPicker|LabeledContent|DisclosureGroup|TextField|'
        r'navigationTitle|accessibilityLabel|accessibilityHint|alert|NSLocalizedString)'
        r'\(\s*("(?:\\.|[^"\\])*")'
        r'|(?:String\(localized:|KeyValueRow\(title:|DetailRawRow\(title:|ResultField\(title:|RawDataSection\(title:)'
        r'\s*("(?:\\.|[^"\\])*")')
    kotlin_calls = re.compile(
        r'(?:tr|Text|ResultField|SavedCardField|SettingsInfoRow|SettingsLinkRow|SettingsActionRow|'
        r'DetailRow|MapStat|ScreenHeader|EmptyPanel|EmptyState)'
        r'\(\s*("(?:\\.|[^"\\])*")'
        r'|(?:title|subtitle|firstLabel|secondLabel|thirdLabel|contentDescription)\s*=\s*("(?:\\.|[^"\\])*")')
    paths = list((ROOT / "ios/CardBal").rglob("*.swift")) + list((ROOT / "android/app/src/main/java").rglob("*.kt"))
    for path in paths:
        if path.name in {"LocalizedResources.kt", "Localization.kt", "Localizer.swift"}:
            continue
        source = path.read_text()
        if path.suffix == ".kt":
            for match in re.finditer(r'(?:Text\(\s*|contentDescription\s*=\s*)("(?:\\.|[^"\\])*")', source):
                raw = match[1]
                if "$" in raw:
                    continue
                text = json.loads(raw)
                if text not in INVARIANTS and re.search(r"[A-Za-z]{2}", text):
                    line = source.count("\n", 0, match.start()) + 1
                    errors.append(f"{path.relative_to(ROOT)}:{line}: wrap UI text in tr(): {text!r}")
        for match in (swift_calls if path.suffix == ".swift" else kotlin_calls).finditer(source):
            raw = next(group for group in match.groups() if group)
            # Compiler extraction verifies Swift interpolation with its exact types.
            if "\\(" in raw or "$" in raw:
                continue
            text = json.loads(raw)
            if not is_covered(text, tables):
                line = source.count("\n", 0, match.start()) + 1
                errors.append(f"{path.relative_to(ROOT)}:{line}: untranslated {text!r}")
    return sorted(set(errors))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--swift-strings", type=Path, help="Directory containing compiler .stringsdata files")
    args = parser.parse_args()
    tables = catalogs()
    errors = check(tables)
    if args.check:
        errors += source_errors(tables)
    if args.swift_strings:
        paths = list(args.swift_strings.glob("*.stringsdata"))
        if not paths:
            errors.append(f"No compiler .stringsdata files in {args.swift_strings}")
        for path in paths:
            for entry in json.loads(path.read_text()).get("tables", {}).get("Localizable", []):
                if entry["key"] not in tables["en"]:
                    errors.append(f"{path.name}: missing compiler key {entry['key']!r}")
    if errors:
        raise SystemExit("\n".join(errors))
    for path, content in outputs(tables).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                errors.append(f"Regenerate {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if errors:
        raise SystemExit("\n".join(errors))
    print(f"{len(tables['en'])} entries, {len(tables)} languages; Android resources match.")


if __name__ == "__main__":
    main()
